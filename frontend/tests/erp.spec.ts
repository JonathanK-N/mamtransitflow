test('Facture émise dans le navigateur et entreprise indépendante',async({page,request})=>{
 const suffix=Date.now(),password='Recette-Finance-392!'
 async function register(label:string,country:string,currency:string){
  const email=`${label}-${suffix}@example.test`
  const response=await request.post('/api/v2/auth/register',{data:{name:'Direction '+label,email,password,organization:{name:'Transport '+label,country,currency,timezone:'Africa/Conakry',activities:['freight']}}})
  expect(response.status()).toBe(201)
  const data=await response.json()
  return {email,headers:{Authorization:'Bearer '+data.access,'X-Organization':data.organizations[0].id}}
 }
 const a=await register('Guinee','GN','GNF'),b=await register('Cameroun','CM','XAF')
 const customerResponse=await request.post('/api/v2/partners',{headers:a.headers,data:{name:'Client recette facturation'}})
 expect(customerResponse.status()).toBe(201)
 const customer=await customerResponse.json()
 await page.goto('/connexion')
 await page.getByLabel('Adresse courriel').fill(a.email)
 await page.getByLabel('Mot de passe',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Se connecter',exact:true}).click()
 await expect(page.locator('.workspace')).toBeVisible()
 await page.locator('.sidebar').getByRole('button',{name:'Facturation',exact:true}).click()
 await page.getByRole('button',{name:'Nouveau',exact:true}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByRole('combobox',{name:/Client/}).selectOption(customer.id)
 await dialog.getByLabel(/^Date/).fill('2026-09-26')
 await dialog.getByLabel(/^Échéance/).fill('2026-10-26')
 await dialog.getByLabel('Description',{exact:true}).fill('Conakry — Kindia')
 await dialog.getByLabel('Prix unitaire',{exact:true}).fill('100')
 await dialog.getByLabel('Taxe (%)',{exact:true}).fill('18')
 await dialog.getByRole('button',{name:'Enregistrer',exact:true}).click()
 await expect(dialog).not.toBeVisible()
 page.once('dialog',d=>d.accept())
 await page.getByRole('button',{name:'Émettre',exact:true}).click()
 await expect(page.locator('tbody .status')).toHaveText('Émise')
 const invoices=await (await request.get('/api/v2/invoices',{headers:a.headers})).json()
 expect(invoices.results[0].total).toBe('118.00')
 const forbidden=await request.get('/api/v2/invoices/'+invoices.results[0].id,{headers:b.headers})
 expect(forbidden.status()).toBe(404)
 const isolated=await (await request.get('/api/v2/invoices',{headers:b.headers})).json()
 expect(isolated.count).toBe(0)
 await page.screenshot({path:'test-results/facturation.png',fullPage:true})
})

